let LANG = "en";
export function lang() { return LANG; }
export function locale() { return LANG === "pt" ? "pt-BR" : "en-US"; }
export function t(key, vars) {
  const entry = D[key];
  let s = entry ? entry[LANG === "pt" ? 1 : 0] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  return s;
}
export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem("faultree.lang"); } catch { /* storage blocked */ }
  const fromUrl = new URLSearchParams(location.search).get("lang");
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
  LANG = fromUrl === "pt" || fromUrl === "en" ? fromUrl : saved === "pt" || saved === "en" ? saved : nav.toLowerCase().startsWith("pt") ? "pt" : "en";
  document.documentElement.lang = LANG === "pt" ? "pt-BR" : "en";
}
export function setLang(l) {
  LANG = l === "pt" ? "pt" : "en";
  document.documentElement.lang = LANG === "pt" ? "pt-BR" : "en";
  try { localStorage.setItem("faultree.lang", LANG); } catch { /* storage blocked */ }
}
// Static text: data-i18n (text), data-i18n-title, data-i18n-aria-label.
export function applyI18n(root) {
  root.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((e) => { e.title = t(e.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((e) => { e.setAttribute("aria-label", t(e.dataset.i18nAriaLabel)); });
  document.title = "faultree — " + t("app.subtitle");
}
